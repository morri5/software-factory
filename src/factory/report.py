"""`make report`: `docs/runs.md`, a Markdown report of every issue's current run.

Per issue: outcome, PR, cost, tool calls (and how many by subagents), factory time
without the approval wait, and the wait itself, then the stage runs. Totals: median cost
per issue, median factory time, and the success rate (a PR opened or merged). Earlier,
abandoned runs of an issue stay in `var/factory.db` but are not part of the report.
"""

import datetime
import sqlite3
import statistics
from pathlib import Path

from factory import config, pr, store

PATH = Path("docs/runs.md")
SUCCESS = ("pr_open", "merged")


def _time(timestamp: str | None) -> datetime.datetime | None:
    if not timestamp:
        return None
    return datetime.datetime.fromisoformat(timestamp.replace("Z", "+00:00"))


def _seconds(start: str | None, end: str | None) -> float | None:
    t0, t1 = _time(start), _time(end)
    return (t1 - t0).total_seconds() if t0 and t1 else None


def duration(seconds: float | None) -> str:
    if seconds is None:
        return "n/a"
    s = round(seconds)
    if s < 60:
        return f"{s} s"
    if s < 3600:
        return f"{s // 60} min {s % 60:02d} s"
    return f"{s // 3600} h {s % 3600 // 60:02d} min"


def approval_wait(issue: sqlite3.Row) -> float | None:
    return _seconds(issue["plan_comment_at"], issue["approved_at"])


def factory_time(issue: sqlite3.Row) -> float | None:
    """Wall time of the run without the approval wait; up to the plan while it waits."""
    if issue["state"] == "awaiting_approval":
        return _seconds(issue["started_at"], issue["plan_comment_at"])
    total = _seconds(issue["started_at"], issue["finished_at"])
    if total is None:
        return None
    return total - (approval_wait(issue) or 0.0)


def _pr(url: str | None) -> str:
    return f"[#{url.rsplit('/', 1)[-1]}]({url})" if url else ""


def render(db: sqlite3.Connection, today: str) -> str:
    issues = db.execute("SELECT * FROM issues ORDER BY number").fetchall()
    runs = {i["number"]: store.current_runs(db, i["number"]) for i in issues}
    costs = [sum(r["cost_usd"] for r in runs[i["number"]]) for i in issues]
    times = [t for i in issues if (t := factory_time(i)) is not None]
    succeeded = sum(i["state"] in SUCCESS for i in issues)
    lines = [
        "# Factory runs",
        "",
        f"Generated by `make report` on {today} from `var/factory.db`, for `{config.REPO}`. "
        "Each issue's current run; factory time excludes the approval wait.",
        "",
        "| Issue | Outcome | PR | Cost | Tool calls (by subagents) | Factory time "
        "| Approval wait |",
        "| --- | --- | --- | ---: | ---: | ---: | ---: |",
    ]
    for issue, cost in zip(issues, costs, strict=True):
        r = runs[issue["number"]]
        calls = sum(x["tool_calls"] for x in r)
        sub = sum(x["subagent_tool_calls"] for x in r)
        lines.append(
            f"| #{issue['number']} {issue['title']} | {issue['state']} | {_pr(issue['pr_url'])} "
            f"| ${cost:.4f} | {calls} ({sub}) | {duration(factory_time(issue))} "
            f"| {duration(approval_wait(issue))} |"
        )
    if issues:
        lines += [
            "",
            f"- Success rate (PR opened or merged): {succeeded} of {len(issues)} "
            f"({succeeded / len(issues):.0%})",
            f"- Median cost per issue: ${statistics.median(costs):.4f}",
            f"- Median factory time: {duration(statistics.median(times) if times else None)}",
        ]
    for issue in issues:
        lines += [
            "",
            f"## #{issue['number']} {issue['title']}",
            "",
            f"Outcome: {issue['state']}. "
            + (f"PR: {_pr(issue['pr_url'])}. " if issue["pr_url"] else "")
            + f"Factory time: {duration(factory_time(issue))}. "
            f"Approval wait: {duration(approval_wait(issue))}.",
            "",
            pr.metrics_table(runs[issue["number"]]),
        ]
    return "\n".join(lines) + "\n"


def write(path: Path = PATH) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(store.connect(), datetime.date.today().isoformat()))
